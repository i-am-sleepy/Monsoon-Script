# Usage (from the repo root):
#   python3 -I tools/gen_fixed_layouts.py
# Reads third_party/avro-reference/layouts/{Probhat,National (Jatiya)}.avrolayout and writes
# app/src/main/kotlin/com/monsoonscript/keyboard/lang/avro/AvroLayoutTables.kt (MPL-2.0 derived data, see third_party/avro-reference/NOTICE.md).
#
# The .avrolayout files are Avro Keyboard's XML key maps: one <Key_<PCKEY>_<Layer>> element per PC key and layer
# (Normal, Shift, AltGr, ShiftAltGr). Numeric keypad elements (Num*) are skipped. The text inside the CDATA is
# double-escaped (a literal "&apos;" for the apostrophe), so every value is html-unescaped once.
import html
import io
import os
import re
import sys
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "third_party", "avro-reference", "layouts")
OUT = os.path.join(ROOT, "app", "src", "main", "kotlin", "com", "monsoonscript", "keyboard", "lang", "avro", "AvroLayoutTables.kt")

# (Kotlin val, FixedLayout id, display name, source file)
LAYOUTS = [
    ("PROBHAT", "probhat", "Probhat", "Probhat.avrolayout"),
    ("NATIONAL", "national", "National (Jatiya)", "National (Jatiya).avrolayout"),
]
LAYERS = ("Normal", "Shift", "AltGr", "ShiftAltGr")
EXPECTED_KEYS = (
    ["OEM3"] + list("1234567890") + ["MINUS", "PLUS"] + list("QWERTYUIOP") + ["OEM4", "OEM6", "OEM5"]
    + list("ASDFGHJKL") + ["OEM1", "OEM7"] + list("ZXCVBNM") + ["COMMA", "PERIOD", "OEM2"]
)

HEADER = """/*
 * This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/.
 *
 * Derived from the Avro Keyboard (OmicronLab) layout files Probhat.avrolayout and National (Jatiya).avrolayout.
 * GENERATED by tools/gen_fixed_layouts.py; see third_party/avro-reference/NOTICE.md. Do not edit by hand.
 */

package com.monsoonscript.keyboard.lang.avro

import com.monsoonscript.keyboard.layout.FixedLayout

/**
 * The fixed Bangla layouts exactly as they are on a PC keyboard: per PC key (Avro's key names) the text of the four layers
 * Normal, Shift, AltGr and Shift+AltGr ("" = nothing). The soft keyboard arranges them for a phone in `layout/Layouts.kt`;
 * a hardware keyboard can look characters up with `FixedLayout.text`.
 */
object AvroLayoutTables {
"""


def kt_str(s):
    out = []
    for ch in s:
        o = ord(ch)
        if 0x20 <= o < 0x7F and ch not in '"\\$':
            out.append(ch)
        elif o <= 0xFFFF:
            out.append("\\u%04X" % o)
        else:
            raise SystemExit("code point above U+FFFF in a layout: %r" % ch)
    return '"' + "".join(out) + '"'


def show(s):
    names = {0x200C: "<ZWNJ>", 0x200D: "<ZWJ>"}
    return "".join(names.get(ord(c), c) for c in s) if s else "-"


def load(path):
    root = ET.fromstring(io.open(path, encoding="utf-8-sig").read())
    table = {}
    for el in root.find("KeyData"):
        m = re.match(r"Key_(.+)_(Normal|Shift|AltGr|ShiftAltGr)$", el.tag)
        if not m:
            continue  # Num1..Num0, NumAdd... (numeric keypad)
        val = html.unescape((el.text or "").strip())
        if len(val) > 1:
            raise SystemExit("%s: %s has more than one character: %r" % (path, el.tag, val))
        table.setdefault(m.group(1), {})[m.group(2)] = val
    missing = [k for k in EXPECTED_KEYS if k not in table or any(l not in table[k] for l in LAYERS)]
    extra = [k for k in table if k not in EXPECTED_KEYS]
    if missing or extra:
        raise SystemExit("%s: missing %s, unexpected %s" % (path, missing, extra))
    return root.findtext("LayoutName").strip(), (root.findtext("DeveloperName") or "").strip(), table


def main():
    parts = [HEADER]
    for val, ident, display, fname in LAYOUTS:
        name, dev, table = load(os.path.join(SRC, fname))
        parts.append("    /** %s, by %s. */\n" % (name, dev))
        parts.append('    val %s = FixedLayout("%s", "%s", arrayOf(\n' % (val, ident, display))
        for k in EXPECTED_KEYS:
            row = [table[k][l] for l in LAYERS]
            parts.append("        arrayOf(%s), // %s\n" % (", ".join(kt_str(x) for x in [k] + row), " ".join(show(x) for x in row)))
        parts.append("    ))\n\n")
    parts[-1] = "    ))\n}\n"
    io.open(OUT, "w", encoding="utf-8", newline="\n").write("".join(parts))
    print("wrote", os.path.relpath(OUT, ROOT))


main()
