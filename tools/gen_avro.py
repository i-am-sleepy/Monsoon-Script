# Usage (from the repo root): python3 -I tools/gen_avro.py third_party/avro-reference/engine app/src/main/kotlin/com/monsoonscript/keyboard/lang/avro
# Generates AvroBanglaChars.kt and AvroRules.kt from the Avro Pascal sources (MPL-2.0 derived output).
import re, sys, io

ENG = sys.argv[1]       # third_party/avro-reference/engine
OUT = sys.argv[2]       # .../lang/avro

HEADER = """/*
 * This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/.
 *
 * Derived from Avro Keyboard (OmicronLab), %s.
 * GENERATED by tools/gen_avro.py from the Pascal source; see third_party/avro-reference/NOTICE.md.
 */
"""

# ---- Bangla chars
src = io.open(ENG + "/BanglaChars.pas", encoding="utf-8-sig", errors="replace").read()
chars = {}   # canonical name -> codepoint
for m in re.finditer(r"^\s*(\w+)\s*:\s*Char\s*=\s*#\$([0-9A-Fa-f]+);", src, re.M):
    chars[m.group(1)] = int(m.group(2), 16)
canon = {k.lower(): k for k in chars}
assert len(canon) == len(chars), "case-insensitive collision in char names"

lines = [HEADER % "BanglaChars.pas", "package com.monsoonscript.keyboard.lang.avro", ""]
lines.append("// Bangla code points used by the Avro phonetic rules (names follow the Pascal constants).")
for k, v in chars.items():
    lines.append('internal const val %s = "\\u%04X"' % (k, v))
io.open(OUT + "/AvroBanglaChars.kt", "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")

# ---- Rules
pas = io.open(ENG + "/clsEnglishToBangla.pas", encoding="utf-8-sig", errors="replace").read()

def body(proc):
    m = re.search(r"^procedure TEnglishToBangla\.%s;\s*\n(.*?)^end;" % re.escape(proc), pas, re.M | re.S)
    assert m, proc
    out = []
    for ln in m.group(1).split("\n"):
        out.append(ln.split("//")[0])
    return "\n".join(out)

CNV = re.compile(r"Cnv\('((?:[^']|'')*)',\s*(.+?)\)\s*=\s*True\s*then")

def kt_str(s):
    s = s.replace("''", "'")
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'

def kt_expr(e):
    toks = [t.strip() for t in e.split(" + ")]
    out = []
    for t in toks:
        if t.startswith("'"):
            out.append(kt_str(t[1:-1]))
        else:
            key = canon[t.lower()]
            out.append(key)
    return " + ".join(out)

PROCS = [("B", "b"), ("C", "c"), ("D", "d"), ("G", "g"), ("H", "h"), ("K", "k"), ("L", "l"),
         ("M", "m"), ("N", "n"), ("P", "p"), ("S", "s"), ("T", "T")]
rl = [HEADER % "clsEnglishToBangla.pas", "package com.monsoonscript.keyboard.lang.avro", "",
      "/**", " * Ordered rule tables: flat arrays of pattern, replacement, pattern, replacement ...",
      " * The first pattern that matches at the current position wins (same order as the Pascal procedures).",
      " */", "internal object AvroRules {"]
total = 0
for kname, proc in PROCS:
    b = body(proc)
    rules = CNV.findall(b)
    assert rules, proc
    total += len(rules)
    rl.append("    /** Rules of the Pascal procedure `%s`. */" % proc)
    rl.append("    @JvmField val %s: Array<String> = arrayOf(" % kname)
    for pat, e in rules:
        rl.append("        %s, %s," % (kt_str(pat), kt_expr(e)))
    rl.append("    )")
    rl.append("")
rl.append("}")
io.open(OUT + "/AvroRules.kt", "w", encoding="utf-8", newline="\n").write("\n".join(rl) + "\n")
print("chars:", len(chars), "rules:", total)
