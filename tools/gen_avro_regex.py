# Usage (from the repo root):
#   python3 -I tools/gen_avro_regex.py third_party/avro-reference/engine app/src/main/kotlin/com/monsoonscript/keyboard/lang/avro
# Generates AvroRegexConstants.kt, AvroRegexRules.kt and AvroBucketMap.kt (MPL-2.0 derived) from the Avro Pascal sources.
import io, re, sys

ENG, OUT = sys.argv[1], sys.argv[2]
HEADER = """/*
 * This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/.
 *
 * Derived from Avro Keyboard (OmicronLab), %s.
 * GENERATED by tools/gen_avro_regex.py from the Pascal source; see third_party/avro-reference/NOTICE.md.
 */
"""

def read(p):
    return io.open(ENG + "/" + p, encoding="utf-8-sig", errors="replace").read()

# Bangla char names (canonical case from BanglaChars.pas)
chars = {}
for m in re.finditer(r"^\s*(\w+)\s*:\s*Char\s*=\s*#\$([0-9A-Fa-f]+);", read("BanglaChars.pas"), re.M):
    chars[m.group(1).lower()] = m.group(1)

def kt_str(s):
    s = s.replace("''", "'")
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'

# ---------------------------------------------------------------- constants (Phonetic_RegExp_Constants.pas)
src = read("Phonetic_RegExp_Constants.pas")
declared = {}
vm = re.search(r"^var\s*\n(.*?)^procedure Initialize_RVals;", src, re.M | re.S)
for name in re.findall(r"\br_\w+", vm.group(1)):
    declared[name.lower()] = name
body = src[src.index("begin", src.index("procedure Initialize_RVals;\n\nimplementation")):]
body = body.split("\nend;")[0]
body = body[len("begin"):] if body.startswith("begin") else body
# keep the {$ELSE} branch (FASTSEARCH_OFF is not defined), drop the IFDEF branch
body = re.sub(r"\{\$IFDEF FASTSEARCH_OFF\}.*?\{\$ELSE\}", "", body, flags=re.S)
body = body.replace("{$ENDIF}", "")
body = re.sub(r"\{[^}]*\}", "", body)  # { comments }
body = "\n".join(l.split("//")[0] for l in body.split("\n"))

stmts = []
i = 0
cur, inq = "", False
for ch in body:
    if ch == "'":
        inq = not inq
    if ch == ";" and not inq:
        stmts.append(cur.strip()); cur = ""
    else:
        cur += ch
assigned = []
lines = [HEADER % "Phonetic_RegExp_Constants.pas", "package com.monsoonscript.keyboard.lang.avro", "",
         "/** Regex fragments for each phonetic unit, built in Pascal order (later ones use earlier ones). */",
         "internal object AvroRegex {"]
for st in stmts:
    m = re.match(r"(r_\w+)\s*:=\s*(.*)$", st, re.S)
    if not m: continue
    name = declared[m.group(1).lower()]
    toks = re.findall(r"'(?:[^']|'')*'|[A-Za-z_]\w*|\+", m.group(2))
    parts = []
    for t in toks:
        if t == "+": continue
        if t.startswith("'"):
            parts.append(kt_str(t[1:-1]))
        elif t.lower().startswith("r_"):
            key = declared[t.lower()]
            assert key in assigned, "forward reference %s in %s" % (key, name)
            parts.append(key)
        else:
            parts.append(chars[t.lower()])
    assigned.append(name)
    lines.append("    @JvmField val %s: String = %s" % (name, " + ".join(parts)))
lines.append("}")
# Kotlin object members referencing Bangla consts need no import (same package, top-level).
# Inside the object the r_ names refer to its own members.
io.open(OUT + "/AvroRegexConstants.kt", "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("constants:", len(assigned))

# ---------------------------------------------------------------- rule tables (clsPhoneticRegExBuilder.pas)
pas = read("clsPhoneticRegExBuilder.pas")
def proc_body(proc):
    m = re.search(r"^procedure TEnglishToRegEx\.%s;\s*\n(.*?)^end;" % proc, pas, re.M | re.S)
    return "\n".join(l.split("//")[0] for l in m.group(1).split("\n"))
CNV = re.compile(r"Cnv\('((?:[^']|'')*)',\s*(r_\w+)\)\s*=\s*True\s*then")
rl = [HEADER % "clsPhoneticRegExBuilder.pas", "package com.monsoonscript.keyboard.lang.avro", "",
      "/** Per-letter pattern -> regex fragment tables (flat arrays, first match wins), except `o` which has a special case. */",
      "internal object AvroRegexRules {"]
total = 0
for L in "ABCDEFGHIJKLMNPQRSTUVWXYZ":
    rules = CNV.findall(proc_body(L))
    assert rules, L
    total += len(rules)
    rl.append("    @JvmField val %s: Array<String> = arrayOf(" % L)
    for pat, r in rules:
        rl.append("        %s, AvroRegex.%s," % (kt_str(pat), declared[r.lower()]))
    rl.append("    )")
rl.append("}")
io.open(OUT + "/AvroRegexRules.kt", "w", encoding="utf-8", newline="\n").write("\n".join(rl) + "\n")
print("rules:", total)

# ---------------------------------------------------------------- first letter -> dictionary buckets (uRegExPhoneticSearch.pas)
ps = read("uRegExPhoneticSearch.pas")
ps = re.sub(r"\{\$IFDEF FASTSEARCH_OFF\}.*?\{\$ENDIF\}", "", ps, flags=re.S)
by_letter = {}
order = []
for m in re.finditer(r"\{ Search W_(\w+) \}\s*\n\s*if (.*?) then\s*\n\s*begin", ps, re.S):
    bucket = m.group(1).lower()
    letters = re.findall(r"mSearchIn = '(\w)'", m.group(2))
    assert letters, bucket
    order.append(bucket)
    for l in letters:
        by_letter.setdefault(l, []).append(bucket)
bl = [HEADER % "uRegExPhoneticSearch.pas", "package com.monsoonscript.keyboard.lang.avro", "",
      "/** Which dictionary buckets (file names under assets/avro/dict, without .txt) hold words that can start a given typed letter. */",
      "internal object AvroBucketMap {",
      "    @JvmField val ALL: Array<String> = arrayOf(" + ", ".join('"%s"' % b for b in order) + ")", "",
      "    /** Buckets to search for a word whose first letter (lower case) is [c]; empty if none. */",
      "    fun forLetter(c: Char): Array<String> = when (c) {"]
for l in sorted(by_letter):
    bl.append("        '%s' -> arrayOf(%s)" % (l, ", ".join('"%s"' % b for b in by_letter[l])))
bl += ["        else -> EMPTY", "    }", "", "    private val EMPTY = emptyArray<String>()", "}"]
io.open(OUT + "/AvroBucketMap.kt", "w", encoding="utf-8", newline="\n").write("\n".join(bl) + "\n")
print("buckets:", len(order), "letters:", len(by_letter))
